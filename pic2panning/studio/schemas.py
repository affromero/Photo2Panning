"""Validated HTTP and worker messages for the local studio."""

from typing import Annotated, Literal

from pydantic import Field, JsonValue, TypeAdapter

from pic2panning.schemas.base import NonEmptyString, PydanticBaseModel, Size
from pic2panning.schemas.creative.composition import ComposeRequest
from pic2panning.schemas.creative.operations import Operation
from pic2panning.schemas.creative.project import (
    ProjectDocument,
    ProjectRequest,
)

type StudioJob = Annotated[
    Operation | ProjectRequest, Field(discriminator="kind")
]
STUDIO_JOB: TypeAdapter[StudioJob] = TypeAdapter(StudioJob)
JSON_OBJECT = TypeAdapter(dict[str, JsonValue])


class Asset(PydanticBaseModel):
    """One local image, video, sound, font, or geometry artifact."""

    path: str
    name: str
    kind: Literal["image", "video", "audio", "font", "data"]
    bytes: int
    width: int | None = None
    height: int | None = None
    duration: float | None = None


class SaveProject(PydanticBaseModel):
    """Save only when the on-disk revision still matches the editor."""

    path: NonEmptyString
    project: ProjectDocument
    expected_revision: Annotated[int, Field(ge=0, strict=True)]


class SavedProject(PydanticBaseModel):
    """Canonical project document and its workspace-relative filename."""

    path: str
    project: ProjectDocument


class JobSubmission(PydanticBaseModel):
    """An immutable validated request queued for a worker process."""

    job: StudioJob


class PreviewSubmission(PydanticBaseModel):
    """Request one canonical frame without executing model operations."""

    composition: ComposeRequest
    frame: Annotated[int, Field(ge=0, strict=True)] = 0


class ReframeSubmission(PydanticBaseModel):
    """Resize a composition through the canonical viewport mapping."""

    composition: ComposeRequest
    size: Size


class DepthAttachment(PydanticBaseModel):
    """Verify an imported companion bundle against an unchanged source."""

    source: NonEmptyString | None = None
    metadata: NonEmptyString


class VerifiedDepth(PydanticBaseModel):
    """A validated cached depth binding ready for a visual layer."""

    metadata: str
    source: str
    focus_metres: float


class JobRecord(PydanticBaseModel):
    """Observable queue state, diagnostics, and published artifact names."""

    id: str
    kind: str
    status: Literal[
        "queued", "running", "completed", "failed", "cancelled"
    ] = "queued"
    submitted: float
    started: float | None = None
    finished: float | None = None
    outputs: tuple[str, ...] = ()
    result: dict[str, JsonValue] | None = None
    error: str | None = None
    log: str = ""


class WorkerResult(PydanticBaseModel):
    """A worker writes this file after its canonical job finishes."""

    result: dict[str, JsonValue] | None = None
    error: str | None = None


class ErrorResponse(PydanticBaseModel):
    """Structured failures shared by every HTTP route."""

    error: str
    message: str


class Bootstrap(PydanticBaseModel):
    """Same-origin initialization with a per-server mutation token."""

    token: str
    workspace: str
    assets: tuple[Asset, ...]
    projects: tuple[str, ...]
    jobs: tuple[JobRecord, ...]


class ValidationResult(PydanticBaseModel):
    """The runtime-normalized request, ready for explicit execution."""

    job: StudioJob
    outputs: tuple[str, ...]


class AssetList(PydanticBaseModel):
    """Discoverable workspace media."""

    assets: tuple[Asset, ...]


class JobList(PydanticBaseModel):
    """An ordered snapshot of all jobs submitted in this server session."""

    jobs: tuple[JobRecord, ...]


class PreviewResult(PydanticBaseModel):
    """Workspace-relative PNG generated by the canonical preview function."""

    path: str
    frame: int
